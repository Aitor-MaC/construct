import Foundation

/// Scripts written into the temporary ZDOTDIR. They are identical for every panel; per-shell
/// choices (nonce, prompt, autosuggestion) arrive through the environment.
enum ZshScripts {
  struct File: Sendable {
    let name: String
    let contents: String
  }

  static let files = [
    File(name: ".zshenv", contents: zshenv),
    File(name: "macterminal.zsh", contents: integration),
  ]

  /// Prompt segment colours of design section 4.5; those without a palette token are only used
  /// by the prompt.
  private enum Segment {
    static let identityBackground = zshColor(MatrixPalette.surface3)
    static let identityText = zshColor(MatrixPalette.fg)
    static let pathBackground = zshColor(MatrixPalette.ph400)
    static let pathText = "#04140A"
    static let gitBackground = "#123D20"
    static let gitText = zshColor(MatrixPalette.ph200)
    static let errorBackground = "#3A1513"
    static let errorText = zshColor(MatrixPalette.ansi[9])
    static let success = zshColor(MatrixPalette.ansi[2])
    static let muted = zshColor(MatrixPalette.muted)
    static let caret = zshColor(MatrixPalette.ph400)
  }

  private static func zshColor(_ color: RGB) -> String {
    String(format: "#%02X%02X%02X", color.red, color.green, color.blue)
  }

  /// Runs first in every zsh started by Macterminal. Moves the nonce into a non-exported shell
  /// variable (children never inherit it), gives the user back their own ZDOTDIR and .zshenv,
  /// and defers the integration to the first precmd so it loads after the user's .zshrc.
  static let zshenv = #"""
    # Generated by Construct. Rewritten on every shell start; do not edit.
    typeset -g +x _mt_nonce="${MACTERMINAL_NONCE-}"
    typeset -g +x _mt_prompt="${MACTERMINAL_PROMPT-0}"
    typeset -g +x _mt_autosuggest="${MACTERMINAL_AUTOSUGGEST-0}"
    typeset -g +x _mt_user_host="${MACTERMINAL_PROMPT_USER_HOST-always}"
    typeset -g +x _mt_path_style="${MACTERMINAL_PROMPT_PATH-full}"
    typeset -g +x _mt_ai_hint_text="${MACTERMINAL_AI_HINT-}"
    typeset -g +x _mt_dir="${ZDOTDIR-}"
    builtin unset MACTERMINAL_NONCE MACTERMINAL_PROMPT MACTERMINAL_AUTOSUGGEST \
      MACTERMINAL_PROMPT_USER_HOST MACTERMINAL_PROMPT_PATH MACTERMINAL_AI_HINT
    if [[ -n "${MACTERMINAL_USER_ZDOTDIR+set}" ]]; then
      builtin export ZDOTDIR="$MACTERMINAL_USER_ZDOTDIR"
      builtin unset MACTERMINAL_USER_ZDOTDIR
    else
      builtin unset ZDOTDIR
    fi
    if [[ -r "${ZDOTDIR:-$HOME}/.zshenv" ]]; then
      builtin source "${ZDOTDIR:-$HOME}/.zshenv"
    fi
    if [[ -o interactive && ${#_mt_nonce} -eq 32 && "$_mt_nonce" != *[^0-9a-f]* ]]; then
      _mt_deferred_init() {
        builtin emulate -L zsh
        # The user's aliases must not change how the integration is parsed.
        builtin setopt no_aliases
        precmd_functions=(${precmd_functions:#_mt_deferred_init})
        builtin unfunction _mt_deferred_init
        builtin source "$_mt_dir/macterminal.zsh" && _mt_activate
      }
      typeset -ga precmd_functions
      precmd_functions+=(_mt_deferred_init)
    fi
    """#

  /// The integration proper. Untrusted data (paths, branch names, commands) never becomes prompt
  /// text: it travels in `psvar` and is referenced with `%Nv`, which zsh prints literally, so
  /// PROMPT_SUBST cannot evaluate it; control characters are replaced before display.
  static let integration = #"""
    # Generated by Construct. Rewritten on every shell start; do not edit.

    _mt_emit() {
      builtin emulate -L zsh
      builtin printf '\e]7777;%s;%s\a' "$_mt_nonce" "${(j:;:)@}"
    }

    _mt_base64() {
      builtin emulate -L zsh
      REPLY=$(builtin print -rn -- "$1" | /usr/bin/base64)
      REPLY=${REPLY//[$'\n\r']/}
    }

    _mt_printable() {
      builtin emulate -L zsh
      REPLY=${1//[[:cntrl:]$'\u0080'-$'\u009f'$'\u200b'-$'\u200f'$'\u202a'-$'\u202e'$'\u2066'-$'\u2069'$'\ufeff']/?}
    }

    _mt_percent_encode() {
      builtin emulate -L zsh
      builtin setopt no_multibyte
      local raw=$1 encoded= char hex
      local -i i
      for (( i = 1; i <= ${#raw}; i++ )); do
        char=${raw[i]}
        if [[ $char == [A-Za-z0-9._~/-] ]]; then
          encoded+=$char
        else
          builtin printf -v hex '%%%02X' "'$char"
          encoded+=$hex
        fi
      done
      REPLY=$encoded
    }

    _mt_format_duration() {
      builtin emulate -L zsh
      local -F seconds=$1
      local -i whole=$seconds
      if (( seconds < 2 )); then
        REPLY=
      elif (( seconds < 60 )); then
        local LC_ALL=C
        builtin printf -v REPLY '%.1f s' $seconds
        REPLY=${REPLY/./,}
      else
        REPLY="$(( whole / 60 )) min $(( whole % 60 )) s"
      fi
    }

    _mt_report_cwd() {
      builtin emulate -L zsh
      if [[ $PWD != "$_mt_cwd" ]]; then
        _mt_cwd=$PWD
        _mt_base64 "$PWD"
        _mt_cwd_base64=$REPLY
        _mt_percent_encode "$HOST"
        _mt_cwd_url="file://$REPLY"
        _mt_percent_encode "$PWD"
        _mt_cwd_url+=$REPLY
      fi
      builtin printf '\e]7;%s\a' "$_mt_cwd_url"
      _mt_emit cwd "$_mt_cwd_base64"
    }

    # Keeps the status reader first and the prompt writer last, even if a theme adds its own
    # precmd hooks later; done from preexec because precmd iterates over the array.
    _mt_order_hooks() {
      builtin emulate -L zsh
      typeset -ga precmd_functions
      precmd_functions=(_mt_precmd_start ${${precmd_functions:#_mt_precmd_start}:#_mt_precmd_end} _mt_precmd_end)
    }

    _mt_precmd_start() {
      local -i last_status=$?
      builtin emulate -L zsh
      _mt_duration=
      if (( _mt_running )); then
        _mt_running=0
        _mt_last_status=$last_status
        builtin printf '\e]133;D;%d\a' $last_status
        _mt_emit D $last_status
        _mt_format_duration $(( EPOCHREALTIME - _mt_started ))
        _mt_duration=$REPLY
      fi
      _mt_report_cwd
    }

    _mt_precmd_end() {
      builtin emulate -L zsh
      # The input mark puts the nonce in the prompt: an rc file or theme that exports it would
      # hand the nonce to every child, so the export is dropped before each prompt.
      builtin typeset -g +x PS1 PROMPT
      if [[ $_mt_prompt == 1 ]]; then
        _mt_git_start
        _mt_prompt_data
        _mt_render_prompt
      elif [[ $PS1 != *"$_mt_mark_input" ]]; then
        PS1+=$_mt_mark_input
      fi
      builtin printf '\e]133;A\a'
      _mt_emit A
    }

    _mt_preexec() {
      builtin emulate -L zsh
      local command=${1:-$3}
      _mt_base64 "$command"
      local -a fields=(C "$REPLY")
      if [[ $command == ' '* ]] || { [[ -n ${HISTORY_IGNORE-} ]] && [[ $command == ${~HISTORY_IGNORE} ]] }; then
        fields+=(nohist)
      fi
      builtin printf '\e]133;C\a'
      _mt_emit "${fields[@]}"
      _mt_running=1
      _mt_started=$EPOCHREALTIME
      _mt_order_hooks
    }

    _mt_prompt_data() {
      builtin emulate -L zsh
      local dir=$PWD time
      if [[ $dir == "$HOME" ]]; then
        dir='~'
      elif [[ $dir == "$HOME"/* ]]; then
        dir="~${dir#"$HOME"}"
      fi
      _mt_printable "$dir"
      _mt_path=$REPLY
      if [[ $_mt_path_style == short ]]; then
        _mt_short_path "$_mt_path"
        _mt_path=$REPLY
      fi
      _mt_identity
      psvar[6]=$REPLY
      psvar[2]=${_mt_git_cache[$PWD]-}
      psvar[3]=
      (( _mt_last_status )) && psvar[3]=$_mt_last_status
      psvar[4]=$_mt_duration
      builtin strftime -s time '%H:%M:%S' $EPOCHSECONDS
      psvar[5]=$time
    }

    # Empty REPLY means no user@host segment. The values are only data: they reach the prompt
    # through psvar like the path, never as prompt text.
    _mt_identity() {
      builtin emulate -L zsh
      REPLY=
      local remote=
      [[ -n ${SSH_CONNECTION-} ]] && remote=1
      case $_mt_user_host in
        (always) ;;
        (ssh) [[ -n $remote ]] || (( EUID == 0 )) || return 0 ;;
        (*) return 0 ;;
      esac
      _mt_printable "$USERNAME@${HOST%%.*}"
      [[ -n $remote ]] && REPLY="⇄ $REPLY"
    }

    # ~/Proyectos Apps/Construct → ~/P/Construct; hidden folders keep their dot.
    _mt_short_path() {
      builtin emulate -L zsh
      local -a parts=("${(@s:/:)1}")
      local -i i
      for (( i = 1; i < ${#parts}; i++ )); do
        if [[ $parts[i] == .* ]]; then
          parts[i]=${parts[i][1,2]}
        else
          parts[i]=${parts[i][1]}
        fi
      done
      REPLY=${(j:/:)parts}
    }

    # Drops whole folders from the left until the path fits in $2 columns; the last folder is
    # always kept, even if it alone is wider. The leading / of an absolute path is the root, not
    # a separator, so / and /usr are never turned into …/ or …/usr.
    _mt_fit_path() {
      builtin emulate -L zsh
      local rest=${1#/}
      local -i columns=$2
      REPLY=$1
      while (( ${(m)#REPLY} > columns )) && [[ $rest == */* ]]; do
        rest=${rest#*/}
        REPLY="…/$rest"
      done
    }

    # Run again when the git segment arrives, so the path is fitted to the final first line.
    _mt_render_prompt() {
      builtin emulate -L zsh
      local separator=$'\ue0b0' previous='\#(Segment.pathBackground)' line=
      # Columns of the first line taken by everything but the path text: the spaces around it
      # and the other segments with their separators.
      local -i used=2
      if [[ -n $psvar[6] ]]; then
        local background='\#(Segment.identityBackground)' text='\#(Segment.identityText)'
        if (( EUID == 0 )); then
          background='\#(Segment.errorBackground)' text='\#(Segment.errorText)'
        fi
        line="%K{$background}%F{$text} %6v %K{\#(Segment.pathBackground)}%F{$background}$separator"
        used+=$(( ${(m)#psvar[6]} + 3 ))
      fi
      line+='%K{\#(Segment.pathBackground)}%F{\#(Segment.pathText)} %1v '
      if [[ -n $psvar[2] ]]; then
        line+="%K{\#(Segment.gitBackground)}%F{$previous}$separator%F{\#(Segment.gitText)} %2v "
        previous='\#(Segment.gitBackground)'
        used+=$(( ${(m)#psvar[2]} + 3 ))
      fi
      if [[ -n $psvar[3] ]]; then
        line+="%K{\#(Segment.errorBackground)}%F{$previous}$separator%F{\#(Segment.errorText)} ✗ %3v "
        line+="%k%F{\#(Segment.errorBackground)}$separator%f"
        used+=$(( ${#psvar[3]} + 6 ))
      else
        line+="%k%F{$previous}$separator%f %F{\#(Segment.success)}✓%f"
        used+=3
      fi
      if [[ -n $psvar[4] ]]; then
        line+=' %F{\#(Segment.muted)}%4v%f'
        used+=$(( ${(m)#psvar[4]} + 1 ))
      fi
      # At least 30 columns of the line stay free, so a long path never fills it.
      _mt_fit_path "$_mt_path" $(( COLUMNS - 30 - used ))
      psvar[1]=$REPLY
      PS1="$line%f%k"$'\n''%F{\#(Segment.caret)}❯ %f'"$_mt_mark_input"
      if (( COLUMNS >= 80 )); then
        RPROMPT='%F{\#(Segment.muted)}%5v%f'
      else
        RPROMPT=
      fi
    }

    _mt_git_start() {
      builtin emulate -L zsh
      _mt_git_stop
      if [[ -z $_mt_git ]] || ! _mt_in_repository; then
        _mt_git_cache[$PWD]=
        return 0
      fi
      _mt_git_output=
      _mt_git_dir=$PWD
      exec {_mt_git_fd}< <(_mt_git_worker "$PWD")
      zle -F -w $_mt_git_fd _mt_git_ready
    }

    _mt_git_stop() {
      builtin emulate -L zsh
      (( _mt_git_fd )) || return 0
      zle -F $_mt_git_fd
      exec {_mt_git_fd}<&-
      _mt_git_fd=0
    }

    # A stat per parent directory instead of starting git in every directory that is not a
    # repository.
    _mt_in_repository() {
      builtin emulate -L zsh
      local dir=$PWD
      while [[ ! -e $dir/.git ]]; do
        [[ $dir == / ]] && return 1
        dir=${dir:h}
      done
    }

    # Without Command Line Tools /usr/bin/git is a shim that opens the install dialog each time
    # it runs, so it is only used when the developer directory really has git.
    _mt_find_git() {
      builtin emulate -L zsh
      typeset -g _mt_git=${commands[git]-}
      [[ $_mt_git == /usr/bin/git ]] || return 0
      local developer
      developer=$(command xcode-select -p 2>/dev/null) && [[ -x $developer/usr/bin/git ]] || _mt_git=
    }

    # Runs in a subshell. Hooks, fsmonitor and optional locks are disabled so a hostile
    # repository cannot run code or stall the prompt; git is killed after 2 s.
    _mt_git_worker() {
      builtin emulate -L zsh
      builtin cd -q -- "$1" 2>/dev/null || return
      GIT_OPTIONAL_LOCKS=0 "$_mt_git" -c core.fsmonitor=false -c core.hooksPath=/dev/null \
        -c core.untrackedCache=false status --porcelain=v2 --branch --no-renames </dev/null 2>/dev/null &
      local -i git_pid=$!
      { zselect -t 200; _mt_git_kill $git_pid } 2>/dev/null &
      local -i watchdog_pid=$!
      wait $git_pid
      local -i git_status=$?
      builtin kill $watchdog_pid 2>/dev/null
      builtin print -r -- "#mt-exit $git_status"
    }

    # With job control the interactive shell runs the worker in its own process group, so the
    # whole group goes: git's children (filters, submodules, wrapper scripts) also hold the
    # output pipe open. Without job control the group is the shell's own, and only git is killed.
    _mt_git_kill() {
      builtin emulate -L zsh
      local worker=$sysparams[ppid] group=${$(/bin/ps -o pgid= -p $1)// /}
      if [[ $group == $worker ]]; then
        builtin kill -KILL -- -$group
      else
        builtin kill -KILL $1
      fi
    }

    _mt_git_ready() {
      builtin emulate -L zsh
      local chunk
      local -i read_status
      while true; do
        sysread -i $1 -t 0 chunk
        read_status=$?
        (( read_status == 0 )) || break
        _mt_git_output+=$chunk
      done
      (( read_status == 5 )) || return 0
      _mt_git_stop
      _mt_git_segment "$_mt_git_output"
      _mt_git_cache[$_mt_git_dir]=$REPLY
      [[ $_mt_git_dir == "$PWD" && $psvar[2] != "$REPLY" ]] || return 0
      psvar[2]=$REPLY
      _mt_render_prompt
      zle reset-prompt
    }

    # Empty REPLY means "not available" (not a repository, error or timeout): no segment.
    _mt_git_segment() {
      builtin emulate -L zsh
      local -a lines=("${(@f)${1%$'\n'}}")
      REPLY=
      [[ ${lines[-1]} == '#mt-exit 0' ]] || return 0
      local line head= oid= ahead=0 behind=0
      local -i changes=0
      for line in "${(@)lines[1,-2]}"; do
        case $line in
          ('# branch.head '*) head=${line#'# branch.head '} ;;
          ('# branch.oid '*) oid=${line#'# branch.oid '} ;;
          ('# branch.ab '*)
            line=${line#'# branch.ab '}
            ahead=${${line%% *}#+}
            behind=${${line##* }#-}
            ;;
          ('#'*) ;;
          (?*) (( changes++ )) ;;
        esac
      done
      [[ $head == '(detached)' ]] && head=${oid[1,7]}
      [[ $ahead == <-> && $behind == <-> ]] || { ahead=0; behind=0 }
      _mt_printable "$head"
      (( changes )) && REPLY+=" ±$changes"
      (( ahead )) && REPLY+=" ↑$ahead"
      (( behind )) && REPLY+=" ↓$behind"
    }

    # REPLY is the request after a leading #, "# " or "??" (blanks trimmed; empty if nothing
    # follows). Fails for any other line, including shebangs and multi-line buffers, which run as
    # usual. Only the main prompt takes requests: in a heredoc, an unclosed quote or vared the
    # line is part of what is being typed.
    _mt_ai_request() {
      builtin emulate -L zsh
      builtin setopt extended_glob
      [[ $CONTEXT == start && $1 != *$'\n'* ]] || return 1
      local line=${1##[[:space:]]#}
      case $line in
        ('#!'*) return 1 ;;
        ('??'*) line=${line#'??'} ;;
        ('#'*) line=${line#'#'} ;;
        (*) return 1 ;;
      esac
      line=${line##[[:space:]]#}
      # Up to the last non-blank: ${line%%[[:space:]]#} is quadratic, and this runs on every key.
      REPLY=${(M)line##*[^[:space:]]}
    }

    # The hint goes on a request line with the cursor at its end, and on the line an empty
    # request has just cleared, so that Return on a bare # still explains itself.
    _mt_wants_ai_hint() {
      builtin emulate -L zsh
      local REPLY
      [[ -n $_mt_ai_hint_text ]] && (( CURSOR == ${#BUFFER} )) || return 1
      [[ -z $BUFFER ]] && (( _mt_ai_hint_pending )) && return 0
      _mt_ai_request "$BUFFER"
    }

    # Its own line-pre-redraw widget, so it works without the autosuggestion. The text was
    # sanitised in _mt_activate; POSTDISPLAY is never expanded as a prompt. Whichever of this and
    # _mt_suggest runs first, each only clears POSTDISPLAY when it holds its own text.
    _mt_show_ai_hint() {
      builtin emulate -L zsh
      [[ -n $BUFFER ]] && _mt_ai_hint_pending=0
      region_highlight=("${(@)region_highlight:#*memo=macterminal-ai}")
      if _mt_wants_ai_hint; then
        POSTDISPLAY=$_mt_ai_hint_text
        region_highlight+=("${#BUFFER} $(( ${#BUFFER} + ${#POSTDISPLAY} )) fg=8,memo=macterminal-ai")
      elif [[ -n $_mt_ai_hint_text && $POSTDISPLAY == "$_mt_ai_hint_text" ]]; then
        POSTDISPLAY=
      fi
    }

    _mt_clear_ai_hint() {
      builtin emulate -L zsh
      _mt_ai_hint_pending=0
      region_highlight=("${(@)region_highlight:#*memo=macterminal-ai}")
      if [[ -n $_mt_ai_hint_text && $POSTDISPLAY == "$_mt_ai_hint_text" ]]; then
        POSTDISPLAY=
      fi
    }

    _mt_suggest() {
      builtin emulate -L zsh
      local suggestion= match
      if _mt_wants_ai_hint; then
        region_highlight=("${(@)region_highlight:#*memo=macterminal}")
        return 0
      fi
      if (( CURSOR == ${#BUFFER} && ${#BUFFER} > 0 )) && [[ $BUFFER != *$'\n'* ]]; then
        match=${history[(r)${(b)BUFFER}?*]}
        [[ $match == *$'\n'* ]] || suggestion=${match:${#BUFFER}}
      fi
      region_highlight=("${(@)region_highlight:#*memo=macterminal}")
      POSTDISPLAY=$suggestion
      if [[ -n $suggestion ]]; then
        region_highlight+=("${#BUFFER} $(( ${#BUFFER} + ${#suggestion} )) fg=8,memo=macterminal")
      fi
    }

    _mt_clear_suggestion() {
      builtin emulate -L zsh
      [[ $_mt_autosuggest == 1 ]] || return 0
      POSTDISPLAY=
      region_highlight=("${(@)region_highlight:#*memo=macterminal}")
    }

    _mt_forward_char() {
      builtin emulate -L zsh
      if (( CURSOR == ${#BUFFER} )) && [[ -n $POSTDISPLAY && $POSTDISPLAY != "$_mt_ai_hint_text" ]]; then
        BUFFER+=$POSTDISPLAY
        CURSOR=${#BUFFER}
        _mt_clear_suggestion
      else
        zle _mt_original_forward_char -- "$@"
      fi
    }

    # A request for the assistant is reported (base64, behind the nonce), never executed; the
    # line is cleared without being accepted, so it never reaches the history.
    _mt_accept_line() {
      builtin emulate -L zsh
      _mt_clear_suggestion
      if _mt_ai_request "$BUFFER"; then
        if [[ -n $REPLY ]]; then
          _mt_base64 "$REPLY"
          _mt_emit ai "$REPLY"
        else
          _mt_ai_hint_pending=1
        fi
        BUFFER=
        return 0
      fi
      zle _mt_original_accept_line -- "$@"
    }

    # clear-screen (Ctrl-L, and the app's Cmd-K) redraws the prompt without running precmd, so
    # the redrawn prompt is announced here. The cursor goes home first so the A mark is anchored
    # on the row where the prompt is about to be drawn, not on the row being cleared.
    _mt_clear_screen() {
      builtin emulate -L zsh
      builtin printf '\e[H\e]133;A\a'
      _mt_emit A
      zle _mt_original_clear_screen -- "$@"
    }

    _mt_activate() {
      builtin emulate -L zsh
      zmodload zsh/datetime zsh/zselect zsh/system zsh/parameter
      autoload -Uz add-zsh-hook add-zle-hook-widget
      typeset -g _mt_mark_input="%{"$'\e]133;B\a\e]7777;'"$_mt_nonce"$';B\a'"%}"
      typeset -gi _mt_running=0 _mt_last_status=0 _mt_git_fd=0
      typeset -g _mt_started= _mt_duration= _mt_cwd= _mt_cwd_base64= _mt_cwd_url= _mt_path=
      typeset -g _mt_git_output= _mt_git_dir=
      typeset -gA _mt_git_cache
      typeset -g _mt_git=
      typeset -gi _mt_ai_hint_pending=0
      # The hint comes from the environment: control characters out, 80 characters at most.
      _mt_printable "$_mt_ai_hint_text"
      _mt_ai_hint_text=${REPLY[1,80]}
      [[ -n $_mt_ai_hint_text ]] && _mt_ai_hint_text="  $_mt_ai_hint_text"
      [[ $_mt_prompt == 1 ]] && _mt_find_git
      _mt_order_hooks
      add-zsh-hook preexec _mt_preexec
      zle -A accept-line _mt_original_accept_line
      zle -N accept-line _mt_accept_line
      zle -A clear-screen _mt_original_clear_screen
      zle -N clear-screen _mt_clear_screen
      zle -N _mt_git_ready
      zle -N _mt_show_ai_hint
      zle -N _mt_clear_ai_hint
      add-zle-hook-widget line-pre-redraw _mt_show_ai_hint
      add-zle-hook-widget line-finish _mt_clear_ai_hint
      if [[ $_mt_autosuggest == 1 ]]; then
        zle -A forward-char _mt_original_forward_char
        zle -N forward-char _mt_forward_char
        zle -N _mt_suggest
        zle -N _mt_clear_suggestion
        add-zle-hook-widget line-pre-redraw _mt_suggest
        add-zle-hook-widget line-finish _mt_clear_suggestion
      fi
      # Already inside the first precmd, whose hook list was fixed before these existed.
      _mt_precmd_start
      _mt_precmd_end
    }
    """#
}
